// Turn a rigged, animated FBX animal (Quaternius' CC0 animal packs, from
// opengameart.org) into a game asset: turned to face +X, scaled to 1 m long,
// standing on y = 0, its clips renamed to plain verbs (idle, walk, run,
// jump, death, …), and written as a base64 GLB to src/assets/animals/<name>.js
// for render3d/chars/animal.js to load (with its skeleton and clips intact).
//
//   node tools/fbx2animal.mjs <in.fbx> <name> [--fwd=x|z|-x|-z]
//
// Runs three's own FBXLoader and GLTFExporter in Node (a FileReader shim is
// all they need); textures aren't loaded: the game paints the models itself.
import fs from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [inp, name, ...rest] = process.argv.slice(2);
if (!inp || !name) { console.error('usage: node tools/fbx2animal.mjs <in.fbx> <name> [--fwd=x|z|-x|-z]'); process.exit(2); }
const opt = Object.fromEntries(rest.map((a) => a.replace(/^--/, '').split('=')));
globalThis.self = globalThis; globalThis.window = globalThis;
globalThis.FileReader = class { readAsArrayBuffer(b) { b.arrayBuffer().then((r) => { this.result = r; this.onloadend?.(); this.onload?.({ target: this }); }); } };
const THREE = await import('three');
const { FBXLoader } = await import('three/examples/jsm/loaders/FBXLoader.js');
const { GLTFExporter } = await import('three/examples/jsm/exporters/GLTFExporter.js');

const buf = fs.readFileSync(inp);
const obj = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '');
obj.traverse((o) => { if (o.isMesh) for (const m of [].concat(o.material)) m.map = null; });
// face +X, 1 m long, feet on the ground
const fwd = opt.fwd || 'z';
obj.rotation.y = { x: 0, '-x': Math.PI, z: Math.PI / 2, '-z': -Math.PI / 2 }[fwd];
obj.updateMatrixWorld(true);
const box = new THREE.Box3().setFromObject(obj);
const s = 1 / (box.max.x - box.min.x);
obj.scale.setScalar(obj.scale.x * s);
obj.updateMatrixWorld(true);
box.setFromObject(obj);
const c = box.getCenter(new THREE.Vector3());
obj.position.set(obj.position.x - c.x, obj.position.y - box.min.y, obj.position.z - c.z);
const wrap = new THREE.Group();
wrap.add(obj);
// clips: plain names, junk (shape-key "Plane" actions) dropped
const clips = [];
for (const a of obj.animations) {
  const n = a.name.split('|').pop().toLowerCase().replace(/action.*$|ing$/, '').replace(/[^a-z]/g, '');
  if (!n || /^plane/.test(n) || a.duration < 0.1) continue;
  a.name = { armature: 'idle', walkslow: 'walkslow' }[n] || (n === 'walk' || n === 'walk' ? 'walk' : n);
  clips.push(a);
}
const glb = await new GLTFExporter().parseAsync(wrap, { binary: true, animations: clips });
const b64 = Buffer.from(glb).toString('base64');
const size = box.getSize(new THREE.Vector3());
const out = join(root, 'src/assets/animals', name + '.js');
fs.writeFileSync(out, `// Generated by tools/fbx2animal.mjs from a CC0 Quaternius model — ${clips.map((a) => a.name).join(', ')}; ${size.toArray().map((v) => v.toFixed(2)).join(' × ')} m. Do not edit.\nexport default '${b64}';\n`);
console.log(name, clips.map((a) => `${a.name}:${a.duration.toFixed(2)}`).join(' '), size.toArray().map((v) => v.toFixed(2)).join('x'), (b64.length / 1024).toFixed(0) + 'KB');
